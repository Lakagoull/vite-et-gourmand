    <h1 class="pt-4">Conditions générales de vente</h1>
    <p class="text-aide">En vigueur au 1er novembre 2026.</p>

    <h2>Article 1 — Objet</h2>
    <p>Les présentes conditions régissent les commandes de menus passées sur le site de Vite &amp; Gourmand, traiteur situé 12 rue Sainte-Catherine à Bordeaux. Toute commande implique l'acceptation des présentes conditions.</p>

    <h2>Article 2 — Commande</h2>
    <p>La commande nécessite la création d'un compte client. Chaque menu doit être commandé pour au moins le nombre minimum de personnes indiqué sur sa fiche, et dans le délai précisé dans ses conditions (par exemple 14 jours avant la prestation). La commande est confirmée par e-mail.</p>
    <p>Chaque menu dispose d'un stock limité de commandes : lorsqu'il est épuisé, le menu ne peut plus être commandé.</p>

    <h2>Article 3 — Prix</h2>
    <p>Les prix sont indiqués en euros toutes taxes comprises. Le prix affiché correspond au nombre minimum de personnes du menu ; il est recalculé selon le nombre de personnes choisi.</p>
    <p>Une <strong>réduction de 10 %</strong> est appliquée sur le prix du menu pour toute commande comptant au moins 5 personnes de plus que le minimum indiqué.</p>

    <h2>Article 4 — Livraison</h2>
    <p>La livraison est gratuite dans la ville de Bordeaux. En dehors de Bordeaux, elle est facturée <strong>5 € majorés de 0,59 € par kilomètre parcouru</strong>. Le détail du prix (menu et livraison) est affiché avant la validation de la commande.</p>

    <h2>Article 5 — Modification et annulation</h2>
    <p>Le client peut modifier (sauf le choix du menu) ou annuler sa commande depuis son espace tant qu'elle n'a pas été acceptée par notre équipe. Après acceptation, toute modification ou annulation doit faire l'objet d'un échange avec Vite &amp; Gourmand, par téléphone ou par e-mail.</p>

    <h2>Article 6 — Prêt de matériel</h2>
    <p>Pour certaines prestations, du matériel (vaisselle, matériel de service) peut être prêté au client. Le client s'engage à le restituer en bon état. Pour cela, il prend contact avec la société afin d'organiser le retour.</p>
    <p><strong>Si le matériel n'est pas restitué dans un délai de 10 jours ouvrés</strong> à compter de la notification envoyée par e-mail, des <strong>frais de 600 €</strong> seront facturés au client.</p>

    <h2>Article 7 — Hygiène et conservation</h2>
    <p>Les plats doivent être conservés selon les précautions indiquées dans les conditions de chaque menu (température, délai de consommation). Vite &amp; Gourmand ne saurait être tenu responsable en cas de non-respect de ces consignes. Les allergènes sont indiqués pour chaque plat.</p>

    <h2>Article 8 — Avis clients</h2>
    <p>Après une commande terminée, le client peut déposer un avis (note de 1 à 5 et commentaire). Les avis sont vérifiés par notre équipe avant publication sur le site.</p>

    <h2>Article 9 — Litiges</h2>
    <p>En cas de litige, une solution amiable sera recherchée en priorité. Le client peut recourir gratuitement à un médiateur de la consommation. À défaut, les tribunaux de Bordeaux seront compétents.</p>
